    public static Vector3 At(double wavelength)
    {
        var (index, fraction) = Locate(wavelength);

        return new Vector3(
            Lerp(Red, index, fraction),
            Lerp(Green, index, fraction),
            Lerp(Blue, index, fraction));
    }

    public static double IlluminantAt(double wavelength)
    {
        var (index, fraction) = Locate(wavelength);

        return Lerp(D65, index, fraction);
    }

    private static (int Index, float Fraction) Locate(double wavelength)
    {
        var position = Math.Clamp((wavelength - First) / Interval, 0.0, Count - 1);
        var index = Math.Min((int)position, Count - 2);

        return (index, (float)(position - index));
    }

    private static float Lerp(ReadOnlySpan<float> table, int index, float fraction)
        => table[index] + (table[index + 1] - table[index]) * fraction;
